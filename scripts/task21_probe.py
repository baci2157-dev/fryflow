"""Задача 21: проба проблемных адресов в Nominatim с разными написаниями.

Вопросы прогона:
  1) «нахичеванские» адреса легли на восток Пролетарского (lng 39.74–39.78,
     Александровка?) — проверить все кандидаты площадей Толстого/Карла Маркса/
     Базарной, Линий, Мясникова, Ченцова, Театрального просп.;
  2) 4 промаха: улицы 1-я/2-я Ковалева и 1-я/2-я Баррикадная — попробовать
     написания с «ё», без «улица», отдельными словами;
  3) контроль: Варфоломеева 60 (запад 39.684?) и Шолохова 145.
"""
import json, time, urllib.parse, urllib.request

def nominatim(query):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode({
        "format": "jsonv2", "limit": "6", "accept-language": "ru",
        "addressdetails": "1", "q": query,
    })
    req = urllib.request.Request(url, headers={"User-Agent": "FryFlowSeedPrep/1.0 (fryflow seed preparation)"})
    with urllib.request.urlopen(req, timeout=6) as r:
        return json.load(r)

PROBES = [
    # ── 1) где реально стоят «нахичеванские» объекты ──
    "площадь Толстого, Ростов-на-Дону",
    "площадь Толстого, 2, Ростов-на-Дону",
    "площадь Карла Маркса, Ростов-на-Дону",
    "площадь Базарная, Ростов-на-Дону",
    "улица 41-я Линия, Ростов-на-Дону",
    "улица Мясникова, Ростов-на-Дону",
    "улица Ченцова, Ростов-на-Дону",
    "Театральный проспект, 48, Ростов-на-Дону",
    "Театральный проспект, Ростов-на-Дону",
    # ── 2) промахи: Ковалева / Баррикадная ──
    "улица 1-я Ковалева, Ростов-на-Дону",
    "улица 1-я Ковалёва, Ростов-на-Дону",
    "1-я Ковалева, 15, Ростов-на-Дону",
    "улица 2-я Ковалёва, Ростов-на-Дону",
    "Ковалева, Ростов-на-Дону",
    "улица 1-я Баррикадная, Ростов-на-Дону",
    "1-я Баррикадная, 12, Ростов-на-Дону",
    "улица 2-я Баррикадная, Ростов-на-Дону",
    "Баррикадная, Ростов-на-Дону",
    # ── 3) контроль западной/уличной точки ──
    "улица Варфоломеева, 60, Ростов-на-Дону",
    "проспект Шолохова, 145, Ростов-на-Дону",
]

for q in PROBES:
    time.sleep(1.1)
    print(f"\n=== {q} ===")
    try:
        res = nominatim(q)
    except Exception as e:
        print(f"  ERROR {e}")
        continue
    if not res:
        print("  (пусто)")
    for c in res[:6]:
        d = (c.get("address") or {}).get("city_district", "")
        print(f"  {float(c['lat']):.6f},{float(c['lon']):.6f} [{c.get('category')}/{c.get('type')}] "
              f"{c['display_name'][:80]} | {d}")
