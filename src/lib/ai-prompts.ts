/** Следующий промпт по кругу: ротация при каждом срабатывании триггера. */
export function nextAdvicePrompt(currentIndex: number): AdvicePrompt {
  const i = ((currentIndex % ADVICE_PROMPTS.length) + ADVICE_PROMPTS.length)
    % ADVICE_PROMPTS.length;
  return ADVICE_PROMPTS[(i + 1) % ADVICE_PROMPTS.length];
}
